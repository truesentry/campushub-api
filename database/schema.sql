-- CampusHub PostgreSQL schema. Target: PostgreSQL 16+.
-- The drop order follows foreign-key dependencies and makes this script repeatable.
DROP TABLE IF EXISTS materials;
DROP TABLE IF EXISTS registrations;
DROP TABLE IF EXISTS events;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT users_name_not_blank CHECK (btrim(name) <> ''),
  CONSTRAINT users_email_lowercase CHECK (email = lower(email))
);

CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  CONSTRAINT categories_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  capacity INTEGER NOT NULL,
  category_id BIGINT NOT NULL,
  CONSTRAINT events_title_not_blank CHECK (btrim(title) <> ''),
  CONSTRAINT events_capacity_positive CHECK (capacity > 0),
  CONSTRAINT events_end_after_start CHECK (ends_at > starts_at),
  CONSTRAINT events_category_fk FOREIGN KEY (category_id)
    REFERENCES categories(id) ON DELETE RESTRICT
);

CREATE TABLE registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  event_id BIGINT NOT NULL,
  registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT registrations_user_event_unique UNIQUE (user_id, event_id),
  CONSTRAINT registrations_user_fk FOREIGN KEY (user_id)
    REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT registrations_event_fk FOREIGN KEY (event_id)
    REFERENCES events(id) ON DELETE CASCADE
);

CREATE TABLE materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL,
  title TEXT NOT NULL,
  url TEXT NOT NULL,
  CONSTRAINT materials_title_not_blank CHECK (btrim(title) <> ''),
  CONSTRAINT materials_url_not_blank CHECK (btrim(url) <> ''),
  CONSTRAINT materials_event_fk FOREIGN KEY (event_id)
    REFERENCES events(id) ON DELETE CASCADE
);
